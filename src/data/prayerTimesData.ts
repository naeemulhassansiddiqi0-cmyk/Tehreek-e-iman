// Helper calculations
export const to12 = (x: string): string => {
  if (!x) return '--:--';
  const [h, m] = x.split(':');
  const H = +h;
  return `${H % 12 || 12}:${m} ${H >= 12 ? 'PM' : 'AM'}`;
};

export const addMins = (time: string, mins: number): string => {
  if (!time) return '00:00';
  const [h, m] = time.split(':').map(Number);
  const d = new Date();
  d.setHours(h, m + mins);
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
};

export const timeToMin = (t: string): number => {
  if (!t) return 0;
  const [h, m] = t.split(':').map(Number);
  return h * 60 + m;
};

export const minToTime = (m: number): string => {
  m = ((m % 1440) + 1440) % 1440;
  const h = Math.floor(m / 60);
  const mm = Math.round(m % 60);
  return `${String(h).padStart(2, '0')}:${String(mm).padStart(2, '0')}`;
};

export function computeTahajjud(ishaTime: string, fajrTime: string): string {
  let isha = timeToMin(ishaTime);
  let fajr = timeToMin(fajrTime);
  if (fajr <= isha) fajr += 1440;
  const duration = fajr - isha;
  const lastThirdStart = fajr - duration / 3;
  return minToTime(lastThirdStart);
}

