export function generateExamNotesPages(slug: string, book: any): string[] {
  const template = EXAM_TEMPLATES[slug] || EXAM_TEMPLATES['exam-notes-daura-hadith'];
  const totalPages = Math.max(book.pages || 50, 50);
  const pages: string[] = [];

  for (let p = 1; p <= totalPages; p++) {
    const topicIndex = (p - 1) % template.topics.length;
    const item = template.topics[topicIndex];
    const qNum = ((p - 1) % 10) + 1;
    const yearHijri = 1435 + ((p * 3) % 11);
    const yearAD = 2014 + ((p * 3) % 11);

    let page = `بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ\n`;
    page += `«${book.title_ar}»\n`;
    page += `[${template.board} • سال ${yearHijri}ھ / ${yearAD}ء • سوال نمبر ${qNum} • صَفْحَة ${p} از ${totalPages}]\n\n`;

    page += `【امتحانی پرچہ و سوال (عربی متن مع اعراب)】\n`;
    page += `${item.qAr}\n\n`;

    page += `【اردو سوالات و امتحانی مطالبات】\n`;
    page += `${item.qUr}\n\n`;

    page += `【سلیس اردو ترجمہ】\n`;
    page += `${item.tarjama}\n\n`;

    page += `【لغوی و صرفی حل (Lughwi & Sarfi Breakdown)】\n`;
    page += item.sarf.join('\n') + `\n\n`;

    page += `【نحوی ترکیب و محلِ اعراب (Nahwi Tarkeeb & Parsing)】\n`;
    page += item.nahw.join('\n') + `\n\n`;

    page += `【درسی و فقہی تشریح مع دلائلِ ائمہ】\n`;
    page += `${item.tashreeh}\n\n`;

    page += `【فوائد و نکاتِ علمیہ】\n`;
    page += item.fawaid.join('\n') + `\n\n`;

    page += `【ممتحن کے خصوصی رہنما مشورے برائے ۱۰۰٪ نمبرات (Examiner Tips)】\n`;
    page += `★ ${item.tip}\n\n`;

    page += `【ماخذ و امتحانی حوالہ】\n`;
    page += `مجموعہ امتحانی پرچہ جات و حل شدہ درسی نوٹس • شعبۂ امتحانات، تحریکِ ایمان (جلد: ${Math.min(book.volumes || 1, Math.ceil(p / 25))}، صفحہ: ${p}).\n`;
    page += `----------------------------------------`;

    pages.push(page.trim());
  }

  return pages;
}
