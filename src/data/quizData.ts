export function getQuizById(id: string): QuizModule | undefined {
  return ALL_QUIZZES.find(q => q.id === id);
}

export function getQuizzesByCategory(categoryKey: string): QuizModule[] {
  return ALL_QUIZZES.filter(q => q.categoryKey === categoryKey);
}

export function getQuizForBookSlug(bookSlug: string): QuizModule[] {
  return ALL_QUIZZES.filter(q => q.bookSlug === bookSlug);
}

export interface QuizScoreRecord {
  quizId: string;
  quizTitle: string;
  score: number;
  totalQuestions: number;
  percentage: number;
  passed: boolean;
  timestamp: number;
}

const QUIZ_SCORES_KEY = 'tehreek_quiz_scores_v1';

export function saveQuizScore(record: QuizScoreRecord): void {
  if (typeof window === 'undefined') return;
  try {
    const raw = localStorage.getItem(QUIZ_SCORES_KEY);
    const list: QuizScoreRecord[] = raw ? JSON.parse(raw) : [];
    // Prepend new score
    const updated = [record, ...list].slice(0, 50);
    localStorage.setItem(QUIZ_SCORES_KEY, JSON.stringify(updated));
    window.dispatchEvent(new CustomEvent('tehreek_quiz_score_saved', { detail: record }));
  } catch (err) {
    console.warn('Failed to save quiz score:', err);
  }
}

export function getQuizScores(): QuizScoreRecord[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(QUIZ_SCORES_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function getBestScoreForQuiz(quizId: string): QuizScoreRecord | null {
  const scores = getQuizScores().filter(s => s.quizId === quizId);
  if (scores.length === 0) return null;
  return scores.reduce((prev, curr) => (curr.percentage > prev.percentage ? curr : prev), scores[0]);
}
