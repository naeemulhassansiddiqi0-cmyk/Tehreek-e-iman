/**
 * Resolves Tarjamah-ul-Bab information dynamically based on chapter title, Hadith number, or book section.
 */
export function getBukhariTarjamahInfo(
  chapterTitleAr: string = '',
  chapterTitleUr: string = '',
  hadithNumber: number = 1,
  pageIndex: number = 0
): TarjamahBabInfo {
  const combined = `${chapterTitleAr} ${chapterTitleUr}`.toLowerCase();

  // 1. Wahy (Hadiths 1-7, Page 0)
  if (hadithNumber <= 7 || combined.includes('وحي') || combined.includes('وحی') || pageIndex === 0) {
    return BUKHARI_TARAJIM_DATABASE['wahy'];
  }

  // 2. Iman (Hadiths 8-58)
  if ((hadithNumber >= 8 && hadithNumber <= 58) || combined.includes('إيمان') || combined.includes('ایمان')) {
    return BUKHARI_TARAJIM_DATABASE['iman'];
  }

  // 3. Ilm (Hadiths 59-134)
  if ((hadithNumber >= 59 && hadithNumber <= 134) || combined.includes('علم')) {
    return BUKHARI_TARAJIM_DATABASE['ilm'];
  }

  // 4. Wudu (Hadiths 135-247)
  if ((hadithNumber >= 135 && hadithNumber <= 247) || combined.includes('وضوء') || combined.includes('وضو')) {
    return BUKHARI_TARAJIM_DATABASE['wudu'];
  }

  // 5. Ghusl (Hadiths 248-293)
  if ((hadithNumber >= 248 && hadithNumber <= 293) || combined.includes('غسل')) {
    return BUKHARI_TARAJIM_DATABASE['ghusl'];
  }

  // 6. Tayammum (Hadiths 334-348)
  if ((hadithNumber >= 334 && hadithNumber <= 348) || combined.includes('تيمم')) {
    return BUKHARI_TARAJIM_DATABASE['tayammum'];
  }

  // 7. Salah (Hadiths 349-1187)
  if ((hadithNumber >= 349 && hadithNumber <= 1187) || combined.includes('صلاة') || combined.includes('نماز') || combined.includes('أذان')) {
    return BUKHARI_TARAJIM_DATABASE['salah'];
  }

  // 8. Zakat (Hadiths 1395-1512)
  if ((hadithNumber >= 1395 && hadithNumber <= 1512) || combined.includes('زكاة') || combined.includes('زکوٰۃ')) {
    return BUKHARI_TARAJIM_DATABASE['zakat'];
  }

  // 9. Sawm (Hadiths 1891-2007)
  if ((hadithNumber >= 1891 && hadithNumber <= 2007) || combined.includes('صوم') || combined.includes('صيام') || combined.includes('روزہ')) {
    return BUKHARI_TARAJIM_DATABASE['sawm'];
  }

  // 10. Hajj (Hadiths 1513-1866)
  if ((hadithNumber >= 1513 && hadithNumber <= 1866) || combined.includes('حج') || combined.includes('عمرة')) {
    return BUKHARI_TARAJIM_DATABASE['hajj'];
  }

  // 11. Buyu (Hadiths 2047-2238)
  if ((hadithNumber >= 2047 && hadithNumber <= 2238) || combined.includes('بيوع') || combined.includes('تجارت') || combined.includes('سود')) {
    return BUKHARI_TARAJIM_DATABASE['buyu'];
  }

  // 12. Nikah (Hadiths 5063-5250)
  if ((hadithNumber >= 5063 && hadithNumber <= 5250) || combined.includes('نكاح') || combined.includes('نکاح')) {
    return BUKHARI_TARAJIM_DATABASE['nikah'];
  }

  // 13. Tawheed (Hadiths 7371-7563)
  if (hadithNumber >= 7371 || combined.includes('توحيد') || combined.includes('توحید')) {
    return BUKHARI_TARAJIM_DATABASE['tawheed'];
  }

  // General Classical Scholarly Synthesis for Any Bukhari Bab
  const babNameAr = chapterTitleAr || 'بَابٌ فِي سُنَنِ النَّبِيِّ ﷺ وَأَحْكَامِ الشَّرِيعَةِ';
  const babNameUr = chapterTitleUr || 'باب: احکامِ شریعت و سننِ نبویہ کا بیان';

  return {
    bookName: 'صَحِيحُ الإِمَامِ الْبُخَارِيِّ رَحِمَهُ اللَّهُ',
    babTitleArabic: babNameAr,
    babTitleUrdu: babNameUr,
    maqsadTarjamah: `امام محمد بن اسماعیل بخاری رحمہ اللہ کا اس ترجمۃ الباب سے مقصود نصوصِ احادیث سے براہِ راست فقہی حکم، استدلال کا طریقہ اور ائمہ مجتہدین کے مابین فہمِ نصوص کا موازنہ قائم کرنا ہے۔ شاہ ولی اللہ محدث دہلوی فرماتے ہیں: «تراجم البخاري ألغاز يتقاصر عنها الأفهام» یعنی امام کے تراجم ایسے علمی رموز ہیں جنہیں حل کرنا تفقہ فی الحدیث کی معراج ہے۔`,
    fiqhiIstinbat: `اس باب کے تحت امام بخاری نے جو احادیث پیش فرمائی ہیں، ان سے فقہائے احناف، شوافع اور دیگر ائمہ کے فروعی استنباطات کی بنیاد فراہم ہوتی ہے۔ طلبۂ درسِ نظامی کو چاہیے کہ وہ حدیث کے الفاظ، محلِ استدلال اور باب کے باہمی ربط پر خصوصی نظر رکھیں۔`,
    muhadditheenAqwal: `علامہ ابن حجر عسقلانی اور علامہ بدر الدین عینی فرماتے ہیں کہ امام بخاری کے قائم کردہ ابواب فقہ الحدیث کا وہ آئینہ ہیں جس سے احادیث کے مخفی فقیہانہ پہلو روشن ہوتے ہیں۔`,
    darsiFaida: `امتحانی و درسی نکتہ: ترجمۃ الباب اور تحت الباب احادیث کے مابین وجہِ مناسبت (مطابقت) تلاش کرنا دورۂ حدیث کے طلبہ کے لیے سب سے اہم علمی آزمائش ہے۔`
  };
}
