const LOCAL_STORAGE_CACHE_KEY = 'tehreek_fiqh_urdu_cache_v5';

/**
 * Read cached translations from localStorage, automatically purging any stale versions or corrupted texts
 */
function getCachedTranslations(): Record<string, string> {
  if (typeof window === 'undefined') return {};
  try {
    // Purge legacy versions
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v1');
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v2');
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v3');
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v4');

    const raw = localStorage.getItem(LOCAL_STORAGE_CACHE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      // Ensure no generic template or "(اس کا)" slipped into cache
      for (const k of Object.keys(parsed)) {
        if (
          parsed[k].includes('اس فقہی عبارت میں') ||
          parsed[k].includes('اس عبارت میں فقہی مسئلہ') ||
          parsed[k].includes('(اس کا)') ||
          parsed[k].includes('(وہ سب)') ||
          parsed[k].includes('(ان کا)')
        ) {
          delete parsed[k];
        }
      }
      return parsed;
    }
  } catch (e) {
    // ignore
  }
  return {};
}

/**
 * Save translation to cache
 */
export function cacheUrduTranslation(cacheKey: string, text: string): void {
  if (typeof window === 'undefined' || !cacheKey || !text) return;
  // Never cache generic template or repetitive (اس کا)
  if (
    text.includes('اس فقہی عبارت میں') ||
    text.includes('اس عبارت میں فقہی مسئلہ') ||
    text.includes('(اس کا)') ||
    text.includes('(وہ سب)') ||
    text.includes('(ان کا)')
  ) return;
  try {
    const current = getCachedTranslations();
    current[cacheKey] = text;
    localStorage.setItem(LOCAL_STORAGE_CACHE_KEY, JSON.stringify(current));
  } catch (e) {
    // ignore
  }
}

