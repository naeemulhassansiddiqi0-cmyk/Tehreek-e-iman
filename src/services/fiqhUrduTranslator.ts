const LOCAL_STORAGE_CACHE_KEY = 'tehreek_fiqh_urdu_cache_v4';

/**
 * Read cached AI translations from localStorage, automatically purging any stale generic templates
 */
function getCachedTranslations(): Record<string, string> {
  if (typeof window === 'undefined') return {};
  try {
    // Purge old versions
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v1');
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v2');
    localStorage.removeItem('tehreek_fiqh_urdu_cache_v3');

    const raw = localStorage.getItem(LOCAL_STORAGE_CACHE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      // Ensure no generic template slipped in
      for (const k of Object.keys(parsed)) {
        if (
          parsed[k].includes('اس فقہی عبارت میں') ||
          parsed[k].includes('اس عبارت میں فقہی مسئلہ')
        ) {
          delete parsed[k];
        }
      }
      return parsed;
    }
  } catch (e) {
    // ignore
  }
  return {};
}

/**
 * Save translation to cache
 */
export function cacheUrduTranslation(cacheKey: string, text: string): void {
  if (typeof window === 'undefined' || !cacheKey || !text) return;
  // Never cache generic template
  if (text.includes('اس فقہی عبارت میں') || text.includes('اس عبارت میں فقہی مسئلہ')) return;
  try {
    const current = getCachedTranslations();
    current[cacheKey] = text;
    localStorage.setItem(LOCAL_STORAGE_CACHE_KEY, JSON.stringify(current));
  } catch (e) {
    // ignore
  }
}

