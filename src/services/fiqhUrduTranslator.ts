/**
 * Clean and normalize text for translation
 */
/**
 * Remove Arabic diacritics (tashkeel, tanween, shaddah, sukoon, tatweel)
 */
export function stripArabicDiacritics(str: string): string {
  if (!str) return '';
  return str.replace(/[\u064B-\u065F\u0670\u0640]/g, '');
}

export function cleanArabicForTranslation(rawText: string): string {
  if (!rawText) return '';
  return rawText
    .replace(/[«»""''()\[\]{}،؛:؟!?]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

