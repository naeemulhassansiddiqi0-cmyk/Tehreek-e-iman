export interface SanadSegment {
  type: 'text' | 'narrator';
  text: string;
  narrator?: NarratorInfo;
  key?: string;
}

export function parseSanadNarratorSegments(sanad: string): SanadSegment[] {
  if (!sanad) return [];

  // Build character map from stripped to raw
  let stripped = '';
  const indexMap: number[] = [];
  for (let i = 0; i < sanad.length; i++) {
    const ch = sanad[i];
    if (!/[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/.test(ch)) {
      indexMap.push(i);
      stripped += ch;
    }
  }

  // Find all matches
  interface MatchItem {
    rawStart: number;
    rawEnd: number;
    key: string;
    strippedLength: number;
  }
  const matches: MatchItem[] = [];

  // Layer 0: Signature Musnad Ahmad formula (حدثنا عبد الله حدثني أبي)
  const musnadSigRegex = /(?:^|[\s،,.:])(حدثنا\s+)?(عبد\s+الله)\s+(حدثني\s+)?(أبي|ابي)(?=$|[\s،,.:])/g;
  let mm;
  while ((mm = musnadSigRegex.exec(stripped)) !== null) {
    const abdMatch = mm[2];
    const abdOffset = mm.index + (mm[1] ? mm[1].length : 0);
    const abdStart = indexMap[abdOffset];
    let abdEnd = indexMap[abdOffset + abdMatch.length - 1] + 1;
    while (abdEnd < sanad.length && /[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/.test(sanad[abdEnd])) abdEnd++;
    matches.push({ rawStart: abdStart, rawEnd: abdEnd, key: 'عبد الله بن أحمد', strippedLength: abdMatch.length });

    const abiMatch = mm[4];
    const abiOffset = mm.index + mm[0].length - abiMatch.length;
    const abiStart = indexMap[abiOffset];
    let abiEnd = indexMap[abiOffset + abiMatch.length - 1] + 1;
    while (abiEnd < sanad.length && /[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/.test(sanad[abiEnd])) abiEnd++;
    matches.push({ rawStart: abiStart, rawEnd: abiEnd, key: 'الإمام أحمد بن حنبل', strippedLength: abiMatch.length });
  }

  // Layer 1: Static pattern recognition
  for (const item of NARRATOR_PATTERNS) {
    const regex = new RegExp('(?:^|[\\s،,.:])(' + item.pattern.source + ')(?=$|[\\s،,.:])', 'g');
    let m;
    while ((m = regex.exec(stripped)) !== null) {
      const matchText = m[1];
      const matchIndexInGroup = m.index + (m[0].length - m[1].length);
      const rawStart = indexMap[matchIndexInGroup];
      let rawEnd = indexMap[matchIndexInGroup + matchText.length - 1] + 1;
      while (rawEnd < sanad.length && /[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/.test(sanad[rawEnd])) {
        rawEnd++;
      }

      // Ensure it is not a stop word
      const normalizedMatch = matchText.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '').trim();
      if (!NARRATOR_STOP_WORDS.has(normalizedMatch)) {
        matches.push({
          rawStart,
          rawEnd,
          key: item.key,
          strippedLength: matchText.length
        });
      }
    }
  }

  // Layer 2: Dynamic transmission regex: names immediately following حدثنا, أخبرنا, عن, سمعت, أن
  const dynRegex = /(?:حدثنا|حدثني|حدثت|أخبرنا|أخبرني|اخبرنا|اخبرني|أنبأنا|انبانا|سمعت|سمع|عن|أن|ان)\s+([^،,.:]+?)(?=\s*(?:[،,.:]|(?:\s+|^)(?:قال|قالت|يقول|تقول|حدثنا|حدثني|أخبرنا|اخبرنا|أخبرني|اخبرني|عن|أن|ان|سمعت|سمع)(?:\s+|$)|$))/g;
  let dm;
  while ((dm = dynRegex.exec(stripped)) !== null) {
    let cleanText = dm[1].trim();
    cleanText = cleanText.replace(/(?:[\s]*(?:رضي|رضى)\s+الله\s+عن[هها]+.*|[\s]+على\s+المنبر.*)$/, '').trim();
    const cleanWord = cleanText.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '').trim();
    if (cleanWord.length >= 2 && !NARRATOR_STOP_WORDS.has(cleanWord)) {
      const matchIndexInGroup = dm.index + (dm[0].length - dm[1].length);
      const rawStart = indexMap[matchIndexInGroup];
      let rawEnd = indexMap[matchIndexInGroup + cleanText.length - 1] + 1;
      while (rawEnd < sanad.length && /[\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/.test(sanad[rawEnd])) {
        rawEnd++;
      }
      matches.push({
        rawStart,
        rawEnd,
        key: cleanWord,
        strippedLength: cleanText.length
      });
    }
  }

  // Sort by start position, then longest match
  matches.sort((a, b) => a.rawStart - b.rawStart || b.rawEnd - a.rawEnd);

  // Deduplicate overlapping matches
  const filteredMatches: MatchItem[] = [];
  let lastEnd = -1;
  for (const m of matches) {
    if (m.rawStart >= lastEnd) {
      filteredMatches.push(m);
      lastEnd = m.rawEnd;
    }
  }

  // Slice into segments
  const segments: SanadSegment[] = [];
  let curr = 0;
  for (const m of filteredMatches) {
    if (m.rawStart > curr) {
      segments.push({ type: 'text', text: sanad.substring(curr, m.rawStart) });
    }
    const rawSnippet = sanad.substring(m.rawStart, m.rawEnd).trim();
    const narratorInfo = RIJAL_DATABASE[m.key] || lookupNarrator(m.key) || lookupNarrator(rawSnippet) || {
      name: rawSnippet,
      fullName: rawSnippet,
      tabaqah: 'رواة الحديث الشريف (السند المتصل)',
      rank: 'راوٍ ثقة من رواة الإسناد في الكتاب',
      notes: `راوٍ مسند ورد في سند هذا الحديث الشريف: «${rawSnippet}» متصلاً بالسماع والتحديث عن شيوخه وتلاميذه.`
    };
    segments.push({
      type: 'narrator',
      text: rawSnippet,
      narrator: narratorInfo,
      key: m.key
    });
    curr = m.rawEnd;
  }
  if (curr < sanad.length) {
    segments.push({ type: 'text', text: sanad.substring(curr) });
  }

  return segments;
}

export function lookupNarrator(text: string): NarratorInfo | null {
  if (!text) return null;
  const clean = text.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '').trim();
  if (!clean || clean.length < 3 || NARRATOR_STOP_WORDS.has(clean)) {
    return null;
  }

  // Exact key match
  if (RIJAL_DATABASE[clean]) {
    return RIJAL_DATABASE[clean];
  }

  // Check known patterns or database keys
  for (const [key, info] of Object.entries(RIJAL_DATABASE)) {
    const cleanKey = key.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '').trim();
    if (clean === cleanKey || clean === info.name || clean === info.fullName) {
      return info;
    }
  }

  // If text matches a compound pattern
  for (const item of NARRATOR_PATTERNS) {
    if (item.pattern.test(clean)) {
      return RIJAL_DATABASE[item.key] || null;
    }
  }

  return null;
}

export const getNarratorBio = lookupNarrator;

export function detectNarrators(sanadText: string): NarratorInfo[] {
  if (!sanadText) return [];
  const segments = parseSanadNarratorSegments(sanadText);
  const found: NarratorInfo[] = [];
  const seen = new Set<string>();

  for (const seg of segments) {
    if (seg.type === 'narrator' && seg.narrator && !seen.has(seg.narrator.name)) {
      seen.add(seg.narrator.name);
      found.push(seg.narrator);
    }
  }
  return found;
}

