  let matchedIraab: { word: string; role: string; sign: string; detail: string } | null = null;

  // 1. Match against contextInfo.mahalIraab if available
  if (contextInfo?.mahalIraab && Array.isArray(contextInfo.mahalIraab)) {
    // Phase A: Exact normalized match
    for (const item of contextInfo.mahalIraab) {
      const itemNorm = normalizeArabicWord(item.word);
      if (norm === itemNorm || cleanRaw === item.word) {
        matchedIraab = item;
        break;
      }
    }
    // Phase B: Stem match if not found
    if (!matchedIraab) {
      for (const item of contextInfo.mahalIraab) {
        const itemNorm = normalizeArabicWord(item.word);
        const itemStem = itemNorm.replace(/^(وال|فال|كال|بال|لل|ال|و|ف|ب|ل|ك)/, '');
        if (stem && (stem === itemStem || stem === itemNorm || norm === itemStem)) {
          matchedIraab = item;
          break;
        }
      }
    }
    // Phase C: Substring match if still not found
    if (!matchedIraab) {
      for (const item of contextInfo.mahalIraab) {
        const itemNorm = normalizeArabicWord(item.word);
        if ((norm.length >= 4 && itemNorm.includes(norm)) || (itemNorm.length >= 4 && norm.includes(itemNorm))) {
          matchedIraab = item;
          break;
        }
      }
    }
  }


