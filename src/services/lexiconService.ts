/**
 * Normalize Arabic text by removing vowels, tatweel, and standardizing letters
 */
export function normalizeArabicWord(word: string): string {
  if (!word) return '';
  return word
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '') // Remove Tashkeel & Quranic stops
    .replace(/[ـ]/g, '')                               // Remove Tatweel
    .replace(/[ٱإأآ]/g, 'ا')                           // Normalize Alif
    .replace(/[ةه]/g, 'ه')                             // Standardize Ta Marbuta / Ha
    .replace(/[ىيئ]/g, 'ي')                            // Standardize Ya / Alif Maqsura
    .replace(/[كک]/g, 'ك')                             // Standardize Arabic / Urdu Kaf
    .replace(/[.,:;!?()،؛؟"«»۝0-9٠-٩]/g, '')           // Remove punctuation & Quran verse markers
    .trim();
}

/**
 * Extract Arabic root triplet from an inflected word (Algorithmic Lemmatizer)
 */
export function extractArabicRoot(normalized: string): string {
  let s = normalized;

  // Strip compound prefixes
  if (s.startsWith('وال') || s.startsWith('فال') || s.startsWith('كال') || s.startsWith('بال') || s.startsWith('لل')) {
    s = s.slice(3);
  } else if (s.startsWith('ال')) {
    s = s.slice(2);
  } else if (s.startsWith('و') || s.startsWith('ف') || s.startsWith('ب') || s.startsWith('ل') || s.startsWith('ك')) {
    if (s.length > 4) s = s.slice(1);
  }

  // Strip suffixes
  if (s.endsWith('هما') || s.endsWith('كما') || s.endsWith('تین') || s.endsWith('تان')) {
    s = s.slice(0, -3);
  } else if (s.endsWith('ين') || s.endsWith('ون') || s.endsWith('ات') || s.endsWith('ها') || s.endsWith('هم') || s.endsWith('كم') || s.endsWith('نا')) {
    s = s.slice(0, -2);
  } else if (s.endsWith('ه') || s.endsWith('ي') || s.endsWith('ت')) {
    if (s.length > 3) s = s.slice(0, -1);
  }

  // Strip verbal prefixes: است، ت، ي، ن، ا، م
  if (s.startsWith('است') && s.length > 5) {
    s = s.slice(3);
  } else if (s.startsWith('ت') && s.length > 4 && s[2] === 'ي') { // تفعيل -> فعل
    return `${s[1]} ${s[3]} ${s[4] || ''}`.trim();
  } else if (s.startsWith('م') && s.length > 4) { // مفعول، مفعل
    s = s.slice(1);
  }

  // If 3 letters remain, treat them as root
  if (s.length === 3) {
    return `${s[0]} ${s[1]} ${s[2]}`;
  }
  if (s.length === 4 && s[1] === 'ا') { // فاعل -> فعل
    return `${s[0]} ${s[2]} ${s[3]}`;
  }
  if (s.length === 4 && s[2] === 'و') { // فعول -> فعل
    return `${s[0]} ${s[1]} ${s[3]}`;
  }
  if (s.length === 4 && s[2] === 'ي') { // فعيل -> فعل
    return `${s[0]} ${s[1]} ${s[3]}`;
  }

  return s.split('').slice(0, 3).join(' ');
}

