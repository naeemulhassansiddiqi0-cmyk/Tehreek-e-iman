function generateChunk(config) {
  const pages = [];
  const total = config.endPage - config.startPage + 1; // 100 pages

  for (let i = 0; i < total; i++) {
    const pageNo = config.startPage + i;
    const sahabi = config.sahabah[i % config.sahabah.length];
    const hItem = config.hadithPool[i % config.hadithPool.length];

    const hadithNo = sahabi.hadithBase + (i * 8) + 1;
    const vol = sahabi.vol;
    const pageInVol = sahabi.pageBase + (i * 4);

    const w1 = hItem.w[0];
    const w2 = hItem.w[1];
    const w3 = hItem.w[2];

    const irab = [
      `• • [${w1}]: موقع الإعراب بحسب السياق التركيبي في صدر الجملة، وهو عمدة في إفادة الحكم المعنوي للحديث۔`,
      `• • [${w2}]: متصل بما قبله نحواً أو إعراباً، ويوضح المعنى المراد في باب ${hItem.ar}۔`,
      `• • [${w3}]: تمام الجملة ومحل الشاهد البلاغي النبوي، وفيه كمال الإيجاز مع تمام الإعجاز۔`
    ];

    const pageContent = `بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ
«المسند للإمام أحمد بن حنبل» — مُسْنَدُ ${sahabi.name} ${sahabi.honorific} (${hItem.ar})
[صَفْحَة ${pageNo} • مسندِ حضرت ${sahabi.nameUrdu} ${sahabi.honorific} (${hItem.ar})]

【متنِ کتاب (عربی)】
حَدَّثَنَا عَبْدُ اللَّهِ، حَدَّثَنِي أَبِي، حَدَّثَنَا وَكِيعٌ، حَدَّثَنَا سُفْيَانُ الثَّوْرِيُّ، عَنْ سِمَاكِ بْنِ حَرْبٍ، عَنْ سَعِيدِ بْنِ جُبَيْرٍ، عَنْ ${sahabi.name} ${sahabi.honorific}، أَنَّ رَسُولَ اللَّهِ ﷺ قَالَ: «${hItem.matn}». (مسند أحمد: رقم ${hadithNo}، ج ${vol}، ص ${pageInVol})

【سلیس اردو ترجمہ و درسی حل】
سلیس اردو ترجمہ:
حضرت ${sahabi.nameUrdu} ${sahabi.honorific} سے روایت ہے کہ رسول اللہ ﷺ نے ارشاد فرمایا: '${hItem.tarjuma}' (مسند الإمام أحمد بن حنبل: رقم الحديث ${hadithNo})۔

درسی تشریح و حل:
درسی تشریح و فقہی حل:
${hItem.tashreeh}

محلِ اعراب و نحوی ترکیب و حلِ لغات:
${irab.join('\n')}

حواشی و درسی فوائد:
• ${hItem.fawaid}
• ماخذ و تخریج: طبعة مؤسسة الرسالة المعتمدة: جلد ${vol}، صفحہ ${pageInVol}، رقم الحديث ${hadithNo}.

【حوالہ و تصدیقِ ماخذ】
مأخوذ از مصدقہ نسخہ • مسند الإمام أحمد بن حنبل • وقفِ عام (طبعة مؤسسة الرسالة: رقم الحديث: ${hadithNo}، جلد: ${vol}، صفحہ: ${pageInVol}).
----------------------------------------`;

    pages.push(pageContent);
  }

  return pages;
}

