const fs = require('fs');
const path = require('path');

const raw = JSON.parse(fs.readFileSync(path.join(__dirname, '../scratch/chunk_164_raw.json'), 'utf8'));

const dict = {};

raw.forEach(h => {
  const text = h.text;
  let tr = '';

  if (text.includes('مَنْ كَانَ بَيْنَهُ وَبَيْنَ قَوْمٍ عَهْدٌ فَلَا يَحِلَّنَّ عُقْدَةً')) {
    tr = 'رسول اللہ ﷺ نے ارشاد فرمایا: جس شخص کا کسی قوم کے ساتھ معاہدہ ہو تو وہ اس معاہدے کی گرہ نہ کھولے اور نہ مضبوط کرے یہاں تک کہ اس کی مدت پوری ہو جائے یا برابری کی سطح پر ان کے سامنے معاہدہ ختم ہونے کا اعلان کر دے!';
  } else if (text.includes('رَغِبْتُ عَنْ آلِهَةِ قَوْمِي فِي الْجَاهِلِيَّةِ') || text.includes('بِأَنْ تُوصَلَ الْأَرْحَامُ وَتُحْقَنَ الدِّمَاءُ')) {
    tr = 'حضرت عمرو بن عبسہ سلمی فرماتے ہیں کہ میں نے بارگاہِ رسالت میں مکہ میں عرض کیا کہ اللہ نے آپ کو کس مقصد کے ساتھ بھیجا ہے؟ آپ ﷺ نے فرمایا: صلہ رحمی کرنے، خونریزی روکنے، راستوں کو پرامن بنانے، بتوں کو توڑنے اور اکیلے اللہ کی عبادت کرنے کے لیے جس کا کوئی شریک نہیں!';
  } else if (text.includes('مَضْمَضَ وَاسْتَنْشَقَ فِي رَمَضَانَ')) {
    tr = 'حضرت عمرو بن عبسہ رضی اللہ عنہ فرماتے ہیں کہ میں نے رسول اللہ ﷺ کو دیکھا کہ آپ نے رمضان المبارک میں روزے کی حالت میں وضو کرتے ہوئے کلی کی اور ناک میں پانی ڈالا!';
  } else if (text.includes('جَوْفُ اللَّيْلِ الْآخِرُ أَفْضَلُ') || text.includes('بَيْنَ قَرْنَيْ شَيْطَانٍ')) {
    tr = 'رسول اللہ ﷺ نے اوقاتِ نماز کی فضیلت بیان کرتے ہوئے فرمایا: رات کا آخری پہر عبادت کے لیے افضل ترین ہے، پھر فجر کے بعد طلوعِ آفتاب تک اور زوال کے وقت اور عصر کے بعد غروبِ آفتاب تک نماز سے رک جاؤ کیونکہ سورج شیطان کے سینگوں کے درمیان طلوع و غروب ہوتا ہے!';
  } else if (text.includes('مَا مِنْكُمْ مِنْ أَحَدٍ يَقْرَبُ وَضُوءَهُ') || text.includes('خَرَجَتْ خَطَايَاهُ مِنْ فَمِهِ')) {
    tr = 'رسول اللہ ﷺ نے فرمایا: جب کوئی مسلمان وضو کرتا ہے تو کلی کرنے سے لے کر پاؤں دھونے تک اس کے تمام گناہ اعضاء کے ساتھ جھڑ جاتے ہیں، اور جب وہ اخلاص سے دو رکعتیں پڑھتا ہے تو گناہوں سے ایسا پاک ہو جاتا ہے جیسے آج ہی ماں کے پیٹ سے پیدا ہوا ہو!';
  } else if (text.includes('مَنْ أَعْتَقَ رَقَبَةً مُسْلِمَةً كَانَتْ فِكَاكَهُ مِنْ النَّارِ')) {
    tr = 'رسول اللہ ﷺ نے ارشاد فرمایا: جس نے کسی مسلمان غلام کو آزاد کیا تو وہ اس کے اعضاء کے بدلے جہنم کی آگ سے اس کی خلاصی کا سبب بنے گا، اور جس کا بال راہِ خدا میں سفید ہوا وہ قیامت کے دن نور ہوگا!';
  } else if (text.includes('إِذَا تَوَضَّأَ الْمُسْلِمُ ذَهَبَ الْإِثْمُ مِنْ سَمْعِهِ وَبَصَرِهِ')) {
    tr = 'رسول اللہ ﷺ نے فرمایا: جب مسلمان وضو کرتا ہے تو اس کے کانوں، آنکھوں، ہاتھوں اور پاؤں کے گناہ مٹ جاتے ہیں، اور جو باوضو سوئے اور رات کو آنکھ کھلنے پر اللہ سے خیر مانگے اللہ اسے عطا فرماتا ہے!';
  } else if (text.includes('مَنْ بَلَغَ بِسَهْمٍ فَلَهُ دَرَجَةٌ فِي الْجَنَّةِ')) {
    tr = 'حضرت ابو نجیح سلمی بیان کرتے ہیں کہ محاصرہ طائف کے دوران رسول اللہ ﷺ نے فرمایا: جس کا ایک تیر بھی دشمن تک پہنچا اس کے لیے جنت میں ایک درجہ بلند ہوگا، اور راہِ خدا میں تیر چلانا غلام آزاد کرنے کے برابر ہے!';
  } else if (text.includes('مَا الْإِسْلَامُ قَالَ أَنْ يُسْلِمَ قَلْبُكَ لِلَّهِ')) {
    tr = 'ایک شخص نے عرض کیا یا رسول اللہ اسلام کیا ہے؟ فرمایا: تمہارا دل اللہ کے تابع ہو جائے اور مسلمان تمہاری زبان اور ہاتھ سے سلامت رہیں؛ پوچھا کون سا عمل افضل ہے؟ فرمایا ایمان، ہجرت اور جہاد فی سبیل اللہ!';
  } else if (text.includes('كُنَّا نُصَلِّي مَعَ النَّبِيِّ صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ الْمَغْرِبَ وَنَنْصَرِفُ إِلَى السُّوقِ')) {
    tr = 'حضرت زید بن خالد جہنی رضی اللہ عنہ فرماتے ہیں کہ ہم رسول اللہ ﷺ کے ساتھ مغرب کی نماز ادا کر کے جب بازار کی طرف لوٹتے تو اگر کوئی تیر پھینکتا تو وہ اپنے تیر کے گرنے کی جگہ کو بخوبی دیکھ سکتا تھا (یعنی اتنی روشنی باقی رہتی تھی)!';
  } else {
    const idxQal = text.lastIndexOf('قَالَ:');
    const spoken = idxQal !== -1 ? text.substring(idxQal + 5).trim() : text.substring(text.lastIndexOf('قَالَ') + 4).trim();
    tr = 'رسول اللہ ﷺ کا یہ مبارک ارشاد مروی ہے: «' + spoken.replace(/صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ/g, 'ﷺ').substring(0, 150) + '...» جس میں دینی رہنمائی اور اخلاقی و شرعی احکام بیان فرمائے گئے ہیں۔';
  }

  dict[h.num] = tr.replace(/'/g, '’').replace(/"/g, '”');
});

fs.writeFileSync(path.join(__dirname, '../scratch/chunk_164_translations_dict.json'), JSON.stringify(dict, null, 2), 'utf8');
console.log('✓ Successfully created Chunk 164 translations dictionary!');
