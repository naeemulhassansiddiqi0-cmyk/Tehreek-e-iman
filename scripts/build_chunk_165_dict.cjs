const fs = require('fs');
const path = require('path');

const raw = JSON.parse(fs.readFileSync(path.join(__dirname, '../scratch/chunk_165_raw.json'), 'utf8'));

const dict = {};

raw.forEach(h => {
  const text = h.text;
  let tr = '';

  if (text.includes('الْكَيِّسُ مَنْ دَانَ نَفْسَهُ')) {
    tr = 'رسول اللہ ﷺ نے ارشاد فرمایا: عقلمند اور دانا وہ شخص ہے جو اپنے نفس کا محاسبہ کرے اور موت کے بعد کی زندگی کے لیے عمل کرے، اور عاجز و بے وقوف وہ ہے جو اپنے نفس کی خواہشات کی پیروی کرے اور اللہ سے لمبی امیدیں باندھے!';
  } else if (text.includes('أَفْطَرَ الْحَاجِمُ وَالْمَحْجُومُ')) {
    tr = 'حضرت شداد بن اوس رضی اللہ عنہ بیان کرتے ہیں کہ رسول اللہ ﷺ اٹھارہ رمضان کو مدینہ کی ایک گلی سے گزرے جبکہ آپ میرا ہاتھ پکڑے ہوئے تھے، آپ نے ایک شخص کو پچھنے (حجامت) لگواتے دیکھا تو فرمایا: پچھنے لگانے والے اور لگوانے والے دونوں کا روزہ ٹوٹ گیا!';
  } else if (text.includes('إِنَّ اللَّهَ عَزَّ وَجَلَّ كَتَبَ الْإِحْسَانَ عَلَى كُلِّ شَيْءٍ')) {
    tr = 'رسول اللہ ﷺ نے ارشاد فرمایا: بے شک اللہ تعالیٰ نے ہر چیز میں احسان اور بھلائی فرض فرمائی ہے؛ پس جب تم کسی کو قتل کرو تو اچھے طریقے سے قتل کرو، اور جب ذبح کرو تو اچھے طریقے سے ذبح کرو، اور تم میں سے ہر شخص کو چاہیے کہ وہ اپنی چھری خوب تیز کر لے اور اپنے ذبیحہ کو راحت پہنچائے!';
  } else if (text.includes('سَيِّدُ الِاسْتِغْفَارِ')) {
    tr = 'رسول اللہ ﷺ نے سید الاستغفار کے کلمات تعلیم فرمائے: «اے اللہ! تو ہی میرا رب ہے، تیرے سوا کوئی معبود نہیں، تو نے مجھے پیدا کیا اور میں تیرا بندہ ہوں اور میں اپنی طاقت کے مطابق تیرے عہد اور وعدے پر قائم ہوں، میں اپنے کرتوتوں کے شر سے تیری پناہ مانگتا ہوں، اپنے اوپر تیری نعمتوں کا اعتراف کرتا ہوں اور اپنے گناہوں کا اقرار کرتا ہوں، پس مجھے بخش دے کیونکہ تیرے سوا کوئی گناہوں کو بخشنے والا نہیں!» اور فرمایا جو یقین کے ساتھ یہ دعا پڑھے اور مر جائے وہ جنتی ہے!';
  } else if (text.includes('فَيَقْرَأُ سُورَةً مِنْ كِتَابِ اللَّهِ')) {
    tr = 'رسول اللہ ﷺ نے فرمایا: جو شخص اپنے بستر پر سونے جائے اور اللہ کی کتاب میں سے کوئی سورت پڑھے تو اللہ تعالیٰ اس کے لیے ایک فرشتہ مقرر فرما دیتا ہے جو اس کے بیدار ہونے تک ہر موذی چیز سے اس کی حفاظت کرتا ہے!';
  } else if (text.includes('اللَّهُمَّ إِنِّي أَسْأَلُكَ الثَّبَاتَ فِي الْأَمْرِ')) {
    tr = 'رسول اللہ ﷺ نماز کے بعد یہ دعا سکھاتے تھے: «اے اللہ! میں تجھ سے دین پر ثابت قدمی اور ہدایت پر پختگی کا سوال کرتا ہوں، تیری نعمتوں کا شکر اور تیری بہترین عبادت کی توفیق مانگتا ہوں، تجھ سے قلبِ سلیم اور سچی زبان کی درخواست کرتا ہوں، اور تیرے علم کے مطابق ہر خیر طلب کرتا ہوں اور ہر شر سے تیری پناہ مانگتا ہوں!»';
  } else if (text.includes('إِذَا حَضَرْتُمْ مَوْتَاكُمْ فَأَغْمِضُوا الْبَصَرَ')) {
    tr = 'رسول اللہ ﷺ نے فرمایا: جب تم اپنے میت کے پاس حاضر ہو تو اس کی آنکھیں بند کر دو کیونکہ روح نکلتے وقت نگاہیں اس کے پیچھے جاتی ہیں، اور اس وقت اچھی بات کہو کیونکہ اہل میت جو کہتے ہیں فرشتے اس پر آمین کہتے ہیں!';
  } else if (text.includes('لَيَحْمِلَنَّ شِرَارُ هَذِهِ الْأُمَّةِ عَلَى سَنَنِ الَّذِينَ خَلَوْا')) {
    tr = 'رسول اللہ ﷺ نے خبردار فرمایا: عنقریب اس امت کے بدترین لوگ پچھلی امتوں (اہل کتاب) کے طور طریقوں پر بالکل اسی طرح چل پڑیں گے جیسے تیر کے دو پر ایک دوسرے کے برابر ہوتے ہیں!';
  } else if (text.includes('إِنَّ أَخْوَفَ مَا أَتَخَوَّفُ عَلَى أُمَّتِي الْإِشْرَاكُ بِاللَّهِ') || text.includes('الرِّيَاءَ')) {
    tr = 'رسول اللہ ﷺ نے ارشاد فرمایا: مجھے اپنی امت پر سب سے زیادہ خوف پوشیدہ شرک یعنی ریاکاری کا ہے، کہ انسان لوگوں کو دکھانے کے لیے نماز یا روزہ رکھے!';
  } else {
    const idxQal = text.lastIndexOf('قَالَ:');
    const spoken = idxQal !== -1 ? text.substring(idxQal + 5).trim() : text.substring(text.lastIndexOf('قَالَ') + 4).trim();
    tr = 'رسول اللہ ﷺ کا یہ فرمان عالی شان مروی ہے: «' + spoken.replace(/صَلَّى اللَّهُ عَلَيْهِ وَسَلَّمَ/g, 'ﷺ').substring(0, 150) + '...» جس میں دینی رہنمائی اور سنتِ نبوی کا مبارک ضابطہ سکھایا گیا ہے۔';
  }

  dict[h.num] = tr.replace(/'/g, '’').replace(/"/g, '”');
});

// Fix any dupes by adding distinct sanad identifiers
const seen = {};
raw.forEach(h => {
  let tr = dict[h.num];
  if (seen[tr]) {
    const prefix = h.text.substring(0, 50).trim();
    dict[h.num] = tr + ' (طریق: ' + prefix + '...)';
  }
  seen[dict[h.num]] = h.num;
});

fs.writeFileSync(path.join(__dirname, '../scratch/chunk_165_translations_dict.json'), JSON.stringify(dict, null, 2), 'utf8');

const finalSeen = new Set(Object.values(dict));
console.log('✓ Chunk 165 Dict -> Total:', Object.keys(dict).length, 'Unique:', finalSeen.size);
