function serializeChapter(ch) {
  let segsCode = ch.segments.map(s => {
    let mahalStr = JSON.stringify(s.mahalIraab, null, 10).replace(/\\n/g, '\\n');
    let hawashiStr = JSON.stringify(s.hawashi, null, 10).replace(/\\n/g, '\\n');
    
    return `      {
        id: '${s.id}',
        arabicText: \`${s.arabicText}\`,
        urduTranslation: \`${s.urduTranslation}\`,
        tashreeh: \`${s.tashreeh}\`,
        mahalIraab: ${mahalStr},
        hawashi: ${hawashiStr}
      }`;
  }).join(',\\n\\n');

  return `  {
    id: '${ch.id}',
    titleArabic: '${ch.titleArabic}',
    titleUrdu: '${ch.titleUrdu}',
    segments: [
${segsCode}
    ]
  }`;
}

